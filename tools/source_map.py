#!/usr/bin/env python3
"""Writes docs/GNX_SOURCE_MAP.md: which GNX/gml file holds what, and every GNX function with its file.

Run after moving functions between files:  python tools/source_map.py
The map is generated from the local GNX/gml sources (git-ignored); the committed map is how contributors who only
have the patches (GNX/diffs) find their way.
"""
import re
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
GML = REPO / "GNX" / "gml"
OUT = REPO / "docs" / "GNX_SOURCE_MAP.md"
FUNC = re.compile(r"^function (\w+)\(", re.M)


def topic(text):
    """the file's first comment line after '// GNX: ' (GNX's own files start with one)"""
    m = re.match(r"// GNX: (.+)", text)
    return m.group(1).strip() if m else ""


def main():
    files = sorted(GML.glob("gml_GlobalScript_s_gnx_*.gml"))
    lines = [
        "# GNX source map",
        "",
        "Where GNX's own GML lives (`GNX/gml/`, shipped as patches in `GNX/diffs/`). Generated by "
        "`python tools/source_map.py`; do not edit by hand.",
        "",
        "Until October 2026 almost all of GNX lived in one file, `gml_GlobalScript_s_initials.gml` (27,000 lines). "
        "It now holds only the game's start-up (`scr_create_initials`, vanilla plus GNX's boot steps); every GNX "
        "function moved, unchanged, into one file per topic below. GML functions are global, so nothing calls "
        "them differently. GNX's changes inside vanilla files (hooks in `s_slot_state`, `s_mon_data`, "
        "`s_button_activate`, ...) did not move: see the patches in `GNX/diffs/`.",
        "",
        "## Files",
        "",
        "| File | What it holds | Functions | Lines |",
        "|---|---|---|---|",
    ]
    index = []
    for f in files:
        text = f.read_text(encoding="utf-8", errors="replace")
        names = FUNC.findall(text)
        if not names:
            continue  # an empty stub (s_gnx_loader)
        short = f.name.replace("gml_GlobalScript_", "")
        lines.append(f"| `{short}` | {topic(text)} | {len(names)} | {text.count(chr(10)) + 1} |")
        index += [(n, short) for n in names]
    init = GML / "gml_GlobalScript_s_initials.gml"
    if init.exists():
        t = init.read_text(encoding="utf-8", errors="replace")
        lines.append(f"| `s_initials.gml` | the game's start-up: vanilla `scr_create_initials` plus GNX's boot steps "
                     f"(registries, mod loading, tests) | {len(FUNC.findall(t))} | {t.count(chr(10)) + 1} |")
    lines += ["", "## Every GNX function", "", "| Function | File |", "|---|---|"]
    for n, f in sorted(index, key=lambda x: x[0].lower()):
        lines.append(f"| `{n}` | `{f}` |")
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    print(f"{OUT.relative_to(REPO)}: {len(files)} files, {len(index)} functions")


if __name__ == "__main__":
    main()
