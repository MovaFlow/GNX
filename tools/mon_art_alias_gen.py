# mon_spr_overrides keys that replace no monster sprite (props, decor, cloth, hands drawn by the cell): nothing for monster_art to lose to
NON_MONSTER_KEYS = ("dairy_blink", "giant_cloth", "shrine_bg", "shrine_dirt", "shrine_sign", "shrine_loop_hand", "shrine_loop_hand_c")


def filter_aliases(draft, picked, hooked, extra):
    out = {}
    for addr, names in draft["addresses"].items():
        if addr.split(".")[1] in LATER_FAMILIES:
            continue
        keep = []
        for n in names:
            if (n in picked or n in hooked) and n not in keep:
                keep.append(n)
        if keep:
            out[addr] = keep
    out.update(extra)
    return out


def gml_function(aliases, old_keys=None, non_monster=()):
    lines = ["// GENERATED by tools/mon_art_alias_gen.py from tools/mon_art_aliases.json: edit that file", "function gnx_art_aliases_build()", "{", "    var _t = {};"]
    for addr in sorted(aliases):
        names = ", ".join(f'"{n}"' for n in aliases[addr])
        lines.append(f'    variable_struct_set(_t, "{addr}", [{names}]);')
    lines += ["    return _t;", "}"]
    if old_keys:  # sprite name -> the old mon_spr_overrides key, from OLD_KEYS above
        src = "// GENERATED from OLD_KEYS in tools/mon_art_alias_gen.py: edit it there"
        lines += ["", "", src, '// the old mon_spr_overrides key that replaces vanilla sprite arg0, or ""', "function gnx_art_old_key(arg0)", "{", "    switch (arg0)", "    {"]
        lines += [f'        case "{n}": return "{old_keys[n]}";' for n in sorted(old_keys)]
        lines += ["    }", "", '    return "";', "}"]
        known = sorted(set(old_keys.values()) | set(non_monster))
        lines += ["", "", "// GENERATED from OLD_KEYS and NON_MONSTER_KEYS in tools/mon_art_alias_gen.py: edit them there",
                  "// true for a mon_spr_overrides key that is in the table above, or that replaces no monster sprite; any other key gets the general log line",
                  "function gnx_art_old_key_known(arg0)", "{", "    switch (arg0)", "    {"]
        lines += [f'        case "{n}": return true;' for n in known]
        lines += ["    }", "", "    return false;", "}"]
    return "\n".join(lines)


def main():
    if "--draft" in sys.argv:
        draft = json.loads((OUT / "alias_draft.json").read_text(encoding="utf-8"))
        picked = set(draft["shared"])
        sys.path.insert(0, str(REPO / "tools"))
        from mon_art_alias_draft import observed_uses
        from mon_art_diff import load
        for base in ("vanilla.base.txt", "old_keys.base.txt"):
            picked |= set(observed_uses(load(OUT / base)))
        ALIASES.write_text(json.dumps(filter_aliases(draft, picked, HOOKED, EXTRA), indent=1, sort_keys=True), encoding="utf-8")
        print("wrote", ALIASES)
        return
    aliases = json.loads(ALIASES.read_text(encoding="utf-8"))
    raw = GML.read_bytes().decode("utf-8")
    eol = "\r\n" if "\r\n" in raw else "\n"  # keep the file's own line endings
    text = raw.replace("\r\n", "\n")
    a, b = text.index(BEGIN) + len(BEGIN), text.index(END)
    text = text[:a] + "\n" + gml_function(aliases, OLD_KEYS, NON_MONSTER_KEYS) + "\n" + text[b:]
    GML.write_bytes(text.replace("\n", eol).encode("utf-8"))
    print(len(aliases), "addresses")


if __name__ == "__main__":
    main()
